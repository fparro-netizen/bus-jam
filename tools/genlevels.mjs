// Builds site/js/levels.js: 36 levels of rising difficulty, each verified solvable with 8 spots and no boosters.
import { generate, solve, randomPlayRate, rng, newState, tap, isWon } from '../site/js/core.js';
import fs from 'fs';
const N = 36;
const lerp = (a, b, t) => a + (b - a) * t;
function cfgFor(i) {
  const t = i / (N - 1);
  const lens = [[2, 4, 10]];
  if (i >= 3) lens.push([3, 6, i < 10 ? 4 : 6]);
  if (i >= 11) lens.push([4, 8, 3]);
  if (i >= 19) lens.push([4, 10, 3]);
  const w = [4, 4, 5, 5, 5, 6][Math.min(5, i)] + (i >= 14 ? 1 : 0);
  const h = Math.min(9, Math.round(lerp(5, 9, Math.min(1, t * 1.4))));
  const area = w * h;
  const avgLen = lens.reduce((a, l) => a + l[0] * l[2], 0) / lens.reduce((a, l) => a + l[2], 0);
  const veh = Math.max(3, Math.min(Math.round(area * lerp(0.5, 0.82, t) / avgLen), Math.round(lerp(3, 24, Math.pow(t, 0.8)))));
  return {
    w, h, veh, lens,
    colors: Math.min(8, 2 + Math.floor(i / 5)),
    cones: i >= 8 ? Math.min(4, 1 + Math.floor((i - 8) / 7)) : 0,
    slots: Math.min(7, 2 + Math.floor(i / 5)),
    gmin: 1, gmax: i < 6 ? 4 : i < 18 ? 3 : 2,
    target: lerp(0.9, 0.12, Math.pow(t, 0.9)),
  };
}
const levels = []; const report = [];
for (let i = 0; i < N; i++) {
  const cfg = cfgFor(i); let best = null;
  for (let c = 0; c < 40; c++) {
    const seed = 1000 * (i + 1) + c * 7919;
    const lv = generate(cfg, seed); if (!lv) continue;
    const sol = solve(lv, 400000); if (!sol.solution) continue;
    const rate = randomPlayRate(lv, 300, rng(seed + 1));
    const score = Math.abs(rate - cfg.target);
    if (!best || score < best.score) best = { lv, rate, score, sol, seed };
    if (score < 0.03) break;
  }
  if (!best) throw new Error('no level ' + i);
  // replay the solver's answer to double check it wins
  const s = newState(best.lv); for (const v of best.sol.solution) if (!tap(s, v).ok) throw new Error('bad sol ' + i);
  if (!isWon(s)) throw new Error('sol does not win ' + i);
  levels.push(best.lv);
  const lv = best.lv;
  report.push({ level: i + 1, w: lv.w, h: lv.h, vehicles: lv.vehicles.length, colors: cfg.colors, cones: lv.blockers.length, people: lv.queue.length, seats: [...new Set(lv.vehicles.map(v => v.seats))].sort((a, b) => a - b).join('/'), randomWin: +best.rate.toFixed(2), target: +cfg.target.toFixed(2), solverNodes: best.sol.nodes, solution: best.sol.solution });
  console.log(JSON.stringify(report[report.length - 1]));
}
const compact = levels.map(l => ({ w: l.w, h: l.h, b: l.blockers, v: l.vehicles.map(v => [v.x, v.y, v.dir, v.len, v.seats, v.color]), q: l.queue.join('') }));
fs.writeFileSync('site/js/levels.js', '// Generated by tools/genlevels.mjs. Every level verified solvable with 8 spots and no boosters.\nconst RAW = ' + JSON.stringify(compact) + ';\nexport const LEVELS = RAW.map(l => ({ w: l.w, h: l.h, blockers: l.b, vehicles: l.v.map(([x, y, dir, len, seats, color]) => ({ x, y, dir, len, seats, color })), queue: l.q.split(\'\').map(Number) }));\n');
fs.writeFileSync('tools/levels-report.json', JSON.stringify(report, null, 1));
