// Builds site/js/levels.js: 36 levels of rising difficulty, each verified solvable with 8 spots and no boosters.
import { generate, solve, randomPlayRate, greedyPlayRate, rng, newState, tap, isWon } from '../site/js/core.js';
import fs from 'fs';
const N = 36;
const lerp = (a, b, t) => a + (b - a) * t;
function cfgFor(i) {
  const t = i / (N - 1);
  const lens = [[2, 8, 10], [3, 16, i < 10 ? 4 : 6]];
  if (i >= 4) lens.push([3, 24, i < 14 ? 2 : 4]);
  const side = Math.round(lerp(10, 16, Math.pow(t, 0.8)));
  const w = side, h = side + (i % 3 === 1 ? 1 : 0);
  const area = w * h;
  const avgLen = lens.reduce((a, l) => a + l[0] * l[2], 0) / lens.reduce((a, l) => a + l[2], 0);
  const veh = Math.max(32, Math.min(90, Math.round(area * lerp(0.74, 0.8, t) / avgLen)));
  return {
    w, h, veh, lens,
    colors: 9,
    cones: 0,
    mystery: i >= 6 ? Math.min(0.25, 0.05 + (i - 6) * 0.007) : 0,
    slots: Math.min(6, 3 + Math.floor(i / 8)),
    gmin: i < 12 ? 8 : 5, gmax: i < 12 ? 24 : 16,
    target: lerp(1, 0.3, Math.pow(t, 1.1)),
  };
}
const levels = []; const report = [];
for (let i = 0; i < N; i++) {
  const cfg = cfgFor(i); let best = null; const t0 = Date.now();
  for (let c = 0; c < 24; c++) {
    const seed = 1000 * (i + 1) + c * 7919;
    const lv = generate(cfg, seed); if (!lv) continue;
    const sol = solve(lv, 300000); if (!sol.solution) continue;
    const rate = greedyPlayRate(lv, 60, rng(seed + 1));
    const score = Math.abs(rate - cfg.target);
    if (!best || score < best.score) best = { lv, rate, score, sol, seed };
    if (score < 0.04) break;
  }
  if (!best) throw new Error('no level ' + i);
  const s = newState(best.lv); for (const v of best.sol.solution) if (!tap(s, v).ok) throw new Error('bad sol ' + i);
  if (!isWon(s)) throw new Error('sol does not win ' + i);
  levels.push(best.lv);
  const lv = best.lv;
  report.push({ level: i + 1, w: lv.w, h: lv.h, vehicles: lv.vehicles.length, colors: cfg.colors, mystery: lv.vehicles.filter(v => v.m).length, riders: lv.queues[0].length + lv.queues[1].length, seats: [...new Set(lv.vehicles.map(v => v.seats))].sort((a, b) => a - b).join('/'), greedyWin: +best.rate.toFixed(2), target: +cfg.target.toFixed(2), solverNodes: best.sol.nodes, ms: Date.now() - t0, solution: best.sol.solution });
  const r = report[report.length - 1]; console.log(JSON.stringify({ ...r, solution: undefined }));
}
const compact = levels.map(l => ({ w: l.w, h: l.h, b: l.blockers, v: l.vehicles.map(v => [v.x, v.y, v.dir, v.len, v.seats, v.color, v.m ? 1 : 0]), q: l.queues.map(q => q.join('')) }));
fs.writeFileSync('site/js/levels.js', '// Generated by tools/genlevels.mjs. Every level verified solvable with 8 spots and no boosters.\nconst RAW = ' + JSON.stringify(compact) + ';\nexport const LEVELS = RAW.map(l => ({ w: l.w, h: l.h, blockers: l.b, vehicles: l.v.map(([x, y, dir, len, seats, color, m]) => ({ x, y, dir, len, seats, color, m })), queues: l.q.map(q => q.split(\'\').map(Number)) }));\n');
fs.writeFileSync('tools/levels-report.json', JSON.stringify(report, null, 1));
