// Builds site/js/levels.js: 36 levels of rising difficulty, each verified solvable with 8 spots and no boosters.
import { generate, solve, greedyPlayRate, rng, newState, toMacro, maskOf, waiting } from '../site/js/core.js';
import fs from 'fs';
const N = 36;
const SHAPES = ['diamond', 'heart', 'circle', 'hexagon', 'heart', 'butterfly'];
const lerp = (a, b, t) => a + (b - a) * t;
function cfgFor(i) {
  const t = i / (N - 1);
  const lens = [[2, 8, 10], [3, 16, i < 10 ? 4 : 6]];
  if (i >= 4) lens.push([3, 24, i < 14 ? 2 : 4]);
  const shape = SHAPES[i % SHAPES.length];
  const base = Math.round(lerp(10, 16.6, Math.pow(t, 0.8)));
  let side = base; while (maskOf(side, side, shape).reduce((a, b) => a + b, 0) < base * base * 1.1) side++;
  const w = side, h = side;
  const area = maskOf(w, h, shape).reduce((a, b) => a + b, 0);
  const avgLen = lens.reduce((a, l) => a + l[0] * l[2], 0) / lens.reduce((a, l) => a + l[2], 0);
  const veh = Math.max(32, Math.min(90, Math.round(base * base * lerp(0.74, 0.8, t) / avgLen)));
  return {
    w, h, shape, veh, lens,
    colors: 9,
    cones: 0,
    mystery: i >= 6 ? Math.min(0.25, 0.05 + (i - 6) * 0.007) : 0,
    slots: 3, gmin: 12, gmax: 24,
    focus: i < 2 ? 0 : Math.min(0.97, lerp(0.4, 1.05, t)),
    target: lerp(1, 0.15, Math.pow(t, 0.9)),
  };
}
const levels = []; const report = [];
for (let i = 0; i < N; i++) {
  const cfg = cfgFor(i); let best = null; const t0 = Date.now();
  for (let c = 0; c < 24; c++) {
    const seed = 1000 * (i + 1) + c * 7919;
    const lv = generate(cfg, seed); if (!lv) continue;
    const sol = solve(lv, 300000); if (!sol.solution) continue;
    const rate = greedyPlayRate(lv, 60, rng(seed + 1), 1); // a player tapping free buses at random
    const score = Math.abs(rate - cfg.target);
    if (!best || score < best.score) best = { lv, rate, score, sol, seed };
    if (score < 0.04) break;
  }
  if (!best) throw new Error('no level ' + i);

  levels.push(best.lv);
  const lv = best.lv;
  report.push({ level: i + 1, shape: lv.shape, w: lv.w, h: lv.h, vehicles: lv.vehicles.length, colors: cfg.colors, mystery: lv.vehicles.filter(v => v.m).length, riders: waiting(newState(lv)), ring: lv.ring.filter(c => c >= 0).length, streams: lv.streams.map(q => q.length), seats: [...new Set(lv.vehicles.map(v => v.seats))].sort((a, b) => a - b).join('/'), greedyWin: +best.rate.toFixed(2), target: +cfg.target.toFixed(2), solverNodes: best.sol.nodes, ms: Date.now() - t0, solution: best.sol.solution });
  const r = report[report.length - 1]; console.log(JSON.stringify({ ...r, solution: undefined }));
}
const compact = levels.map(l => ({ w: l.w, h: l.h, b: l.blockers, v: l.vehicles.map(v => [v.x, v.y, v.dir, v.len, v.seats, v.color, v.m ? 1 : 0]), s: l.shape, r: l.ring.map(c => c < 0 ? '.' : c).join(''), q: l.streams.map(q => q.join('')) }));
fs.writeFileSync('site/js/levels.js', '// Generated by tools/genlevels.mjs. Every level verified solvable with 8 spots and no boosters.\nconst RAW = ' + JSON.stringify(compact) + ';\nexport const LEVELS = RAW.map(l => ({ w: l.w, h: l.h, blockers: l.b, vehicles: l.v.map(([x, y, dir, len, seats, color, m]) => ({ x, y, dir, len, seats, color, m })), shape: l.s, ring: l.r.split(\'\').map(c => c === \'.\' ? -1 : +c), streams: l.q.map(q => q.split(\'\').map(Number)) }));\n');
fs.writeFileSync('tools/levels-report.json', JSON.stringify(report, null, 1));
